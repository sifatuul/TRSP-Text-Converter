function replAll(s,a,b){ return s.split(a).join(b); }

function normalizePunctuation(s){
  return s
    .normalize('NFC')
    .replace(/•/g, '·')
    // Common Unicode subscript digits pasted from science books.
    .replace(/₀/g,'0').replace(/₁/g,'1').replace(/₂/g,'2').replace(/₃/g,'3').replace(/₄/g,'4')
    .replace(/₅/g,'5').replace(/₆/g,'6').replace(/₇/g,'7').replace(/₈/g,'8').replace(/₉/g,'9');
}

function reorderForBijoy(s){
  s=s.replace(/ো/g,'\uE000া').replace(/ৌ/g,'\uE001ৗ');
  const cons='[ক-হড়ঢ়য়ৎ]';
  const cluster=`${cons}(?:্${cons})*`;
  s=s.replace(new RegExp(`(${cluster})([িেৈ\uE000\uE001])`,'g'),'$2$1');
  s=s.replace(new RegExp(`([িেৈ]?)(র্)(${cluster})`,'g'),'$1$3$2');
  s=s.replace(new RegExp(`(${cluster})([াুূীৃোৌৗ])©`,'g'),'$1$2©');
  s=s.replace(/ড়/g,'ড়').replace(/ঢ়/g,'ঢ়').replace(/য়/g,'য়');
  return s;
}

function unicodeToBijoy(text){
  if(!text) return '';
  let r=normalizePunctuation(text);
  r=reorderForBijoy(r);
  for(const [u,b] of U2B_MULTI) r=replAll(r,u,b);
  let out='';
  for(const ch of r) out += U2B_SINGLE[ch] ?? ch;

  // Safe post-fixes used by legacy Bijoy/SutonnyMJ text.
  out=out.replace(/Avv/g,'Av').replace(/ww/g,'w').replace(/xx/g,'x').replace(/zz/g,'z').replace(/~~/g,'~');
  out=out.replace(/\uE000/g,'‡').replace(/\uE001/g,'‡');
  out=out.replace(/q‡/g,'‡q').replace(/o‡/g,'‡o');
  // Common publishing spelling: ‘থেকে’ is conventionally emitted as †_‡K.
  out=out.replace(/(^|[\s·])‡_‡K/g,'$1†_‡K');
  return out;
}

