function replAll(s,a,b){return s.split(a).join(b)}
function reorderForBijoy(s){
  // o/au kar -> e + aa/ou before rearrangement
  s=s.replace(/ো/g,'ো').replace(/ৌ/g,'ৌ');
  // Move left-side vowel signs before their consonant cluster.
  const cons='[ক-হড়ঢ়য়ৎ]';
  const cluster=`${cons}(?:্${cons})*`;
  s=s.replace(new RegExp(`(${cluster})([িেৈ])`,'g'),'$2$1');
  // Reph: র্ + cluster -> cluster + reph marker. Preserve leading kar.
  s=s.replace(new RegExp(`([িেৈ]?)(র্)(${cluster})`,'g'),'$1$3$2');
  // Legacy Bijoy expects reph after the cluster; if a post-kar follows, keep it before reph.
  s=s.replace(new RegExp(`(${cluster})([াুূীৃোৌৗ])©`,'g'),'$1$2©');
  s=s.replace(/ড়/g,'ড়').replace(/ঢ়/g,'ঢ়').replace(/য়/g,'য়');
  return s;
}
function unicodeToBijoy(text){
 if(!text)return '';
 let r=text.normalize('NFC').replace(/[“”]/g,'"').replace(/[‘’]/g,"'").replace(/…/g,'...').replace(/[–—]/g,'-');
 r=r.replace(/য়/g,'য়').replace(/ড়/g,'ড়').replace(/ঢ়/g,'ঢ়');
 r=reorderForBijoy(r);
 for(const [u,b] of U2B_MULTI) r=replAll(r,u,b);
 let out=''; for(const ch of r) out += U2B_SINGLE[ch]??ch;
 // common post fixes
 out=out.replace(/Avv/g,'Av').replace(/ww/g,'w').replace(/xx/g,'x').replace(/yy/g,'y').replace(/~~/g,'~');
 out=out.replace(/q‡/g,'‡q').replace(/o‡/g,'‡o');
 return out;
}
